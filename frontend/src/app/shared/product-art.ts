interface WandSheet {
  url: string;
  width: number;
  height: number;
  greyMatte?: boolean;
}

type Crop = readonly [x: number, y: number, width: number, height: number];

interface WandArt {
  sheet: WandSheet;
  crop: Crop;
  kind: 'reference' | 'illustration';
  outline?: string;
}

const labeledReference = { url: '/assets/wands/reference-labeled.png', width: 656, height: 750, greyMatte: true };
