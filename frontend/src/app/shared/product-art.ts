const originalIllustrations = { url: '/assets/wands/original-wands.png', width: 2172, height: 724 };

function reference(y: number, height: number): WandArt {
  return { sheet: labeledReference, crop: [130, y, 512, height], kind: 'reference' };
}

function illustration(column: number, row: number, outline: string): WandArt {
  const width = originalIllustrations.width / 3;
  const height = originalIllustrations.height / 3;
  return {
    sheet: originalIllustrations,
    crop: [column * width, row * height, width, height],
    kind: 'illustration',
    outline,
  };
}

